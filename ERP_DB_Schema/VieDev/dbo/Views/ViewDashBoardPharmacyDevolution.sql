

CREATE VIEW [dbo].[ViewDashBoardPharmacyDevolution]
AS
with HD as(
select CODCONCEC, CODPRODUC from HCDEVMEDD h
where CANPENDIE>0
),
IHLISTPRO_ AS(
SELECT H.TIPPRODUC, CODCONCEC FROM HD
JOIN IHLISTPRO H ON H.CODPRODUC = HD.CODPRODUC
),
MEDICAMENTOS AS(
select TIPPRODUC, H.CODCONCEC from IHLISTPRO_ H
WHERE H.TIPPRODUC=1
GROUP BY H.TIPPRODUC, CODCONCEC
),
INSUMOS AS(
select TIPPRODUC, H.CODCONCEC from IHLISTPRO_ H
WHERE H.TIPPRODUC=2
GROUP BY H.TIPPRODUC, CODCONCEC
),
MEDICAMENTOS_INSUMOS AS(
select TIPPRODUC, H.CODCONCEC from IHLISTPRO_ H
WHERE H.TIPPRODUC=3
GROUP BY H.TIPPRODUC, CODCONCEC
)

SELECT	A.CODCONCEC as Row ,
		0 AS SelectOption, 
		A.CODCENATE AS CodigoCentroAtencion,
		A.CODCONCEC AS ConsecutivoDevoluciones, 
		A.FECHDEVOL AS FechaDevolucion, 
		A.CODPROSAL AS CodigoProfesional,
		A.IPCODPACI AS CodigoPaciente,
		A.NUMINGRES AS Ingreso, 
		A.CODCENATE AS CentroAtencion,
		A.UFUCODIGO, 
		A.DEVESTADO AS Estado,
		RTRIM(A.CODCENCOS) AS CentroCostos, 
		A.ORIDEVMED,
		A.FECREGISTR,
		A.CODUSUARI,
		RTRIM(B.IPNOMCOMP) AS NombrePaciente,
		RTRIM(D.UFUDESCRI) AS UnidadFuncional,
		RTRIM(C.NOMMEDICO) AS NombreMedico, 
		concat(rtrim( bo.CODBODEGA),' - ',rtrim(bo.DESBODEGA)) AS Bodega, 
		CASE ORIDEVMED 
			WHEN 1 THEN 'Traslado de Cama Hospitalizacion'
			WHEN 2 THEN 'Egreso de Cama Hospitalizacion'
			WHEN 5 THEN 'Hoja de Gasto QX' 
			ELSE 'Enfermeria (Devolutivo Parcial)' 
		END AS OrigenDevolutivo, 
		CAST('' AS bit) AS ImpresionDev,
		ISNULL(cama.NUMCAMHOS, '') AS CodigoCama, 
		RTRIM(LTRIM(A.CODCENATE)) + ' - ' + RTRIM(LTRIM(cent.NOMCENATE)) CareCenterDescription,
		dbo.GetProfessionType(C.TIPPROFES) Profesion,
		B.IPFECNACI BirthDay,
		IIF(M.TIPPRODUC>0, 1,0) MEDICAMENTO,
		IIF(I.TIPPRODUC>0, 1,0) INSUMOS,
		IIF(MI.TIPPRODUC>0, 1,0) MEDICAMENTO_INSUMO
FROM dbo.HCDEVMEDC AS A 
JOIN dbo.IHBODEGAS as bo on a.CODBODEGA = bo.CODBODEGA 
JOIN dbo.INPACIENT AS B ON A.IPCODPACI = B.IPCODPACI 
JOIN dbo.INPROFSAL AS C ON A.CODPROSAL = C.CODPROSAL 
JOIN dbo.INUNIFUNC AS D ON A.UFUCODIGO = D.UFUCODIGO 	
JOIN dbo.ADCENATEN cent WITH(NOLOCK) on cent.CODCENATE = A.CODCENATE 
JOIN dbo.ADINGRESO as ING WITH(NOLOCK) ON A.NUMINGRES = ING.NUMINGRES 
LEFT JOIN dbo.CHCAMASHO cama ON ISNULL(CASE WHEN ING.CODCAMACT = 0 THEN '' ELSE CAST(ING.CODCAMACT AS VARCHAR(15)) END, '') = cama.CODICAMAS
LEFT JOIN MEDICAMENTOS M ON M.CODCONCEC = A.CODCONCEC
LEFT JOIN INSUMOS I ON I.CODCONCEC = A.CODCONCEC
LEFT JOIN MEDICAMENTOS_INSUMOS MI ON MI.CODCONCEC = A.CODCONCEC
WHERE (A.DEVESTADO = '1')