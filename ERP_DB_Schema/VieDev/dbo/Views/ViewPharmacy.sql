





CREATE VIEW [dbo].[ViewPharmacy]
AS

with HD as(
select CODCONCEC,Stat, CODPRODUC from HCFARMEPD WITH(NOLOCK)
where CANPENPRO>0
),
STAT AS(
SELECT CODCONCEC,Stat from HD
WHERE Stat=1
GROUP BY CODCONCEC,Stat
),
IHLISTPRO_ AS(
SELECT H.TIPPRODUC, CODCONCEC FROM HD
JOIN IHLISTPRO H ON H.CODPRODUC = HD.CODPRODUC
),
MEDICAMENTOS AS(
select TIPPRODUC, H.CODCONCEC from IHLISTPRO_ H
WHERE H.TIPPRODUC=1
GROUP BY H.TIPPRODUC, CODCONCEC
),
INSUMOS AS(
select TIPPRODUC, H.CODCONCEC from IHLISTPRO_ H
WHERE H.TIPPRODUC=2
GROUP BY H.TIPPRODUC, CODCONCEC
),
MEDICAMENTOS_INSUMOS AS(
select TIPPRODUC, H.CODCONCEC from IHLISTPRO_ H
WHERE H.TIPPRODUC=3
GROUP BY H.TIPPRODUC, CODCONCEC
)

	SELECT	A.CODCONCEC,
			A.CODCONCEP,
			A.CODCONCES,
			A.FECHAORDE, 
			A.CODCENATE, 
			A.UFUCODIGO,
			A.CODCENCOS,
			A.IPCODPACI,
			A.NUMINGRES,
			A.NUMEFOLIO,
			A.IDETIPHIS,
			CASE WHEN A.MedicalOrderType = 2 THEN '3' -- en caso de que sea PRN
			WHEN ISNULL(A.MedicalOrderType,1)=1 AND ISNULL(STAT.Stat,0)=1 THEN '4' -- En caso de que sea inmediatamente
			WHEN A.ORDTRANUE=3 THEN '5'
			ELSE A.ORDTRANUE 
			END AS ORDTRANUE,
			ISNULL(A.TIPOSOLICITUD, 0) TIPOSOLICITUD,
			A.MEDICAMENTOVALIDADO,
			A.CODBODEGA,
			A.CODPROSAL,
			ING.CODCAMACT,
			A.ORDESTADO,
			ISNULL(cg.ExtramuralPharmaceuticalDispensing,0) TIPOSOLICITUD1, 
			Cg.ExtramuralPharmaceuticalDispensing as PERMITEEXTRA,
			ISNULL((select top 1 1
			from dbo.HCFARMEPD hd
			WHERE hd.CODCONCEC =A.CODCONCEC AND hd.CANPENPRO>0 AND hd.VIEPROCESSED =0
			),0) as HasQuantityRemaining,
			0 PatientDischarge,
			M.TIPPRODUC AS MEDICAMENTO,
			I.TIPPRODUC AS INSUMOS,
			MI.TIPPRODUC AS MEDICAMENTO_INSUMO
	FROM dbo.HCFARMEPC AS A WITH (NOLOCK)
	JOIN dbo.ADINGRESO as ING WITH (NOLOCK) ON A.NUMINGRES = ING.NUMINGRES
	LEFT JOIN Contract.CareGroup cg WITH (NOLOCK) ON ING.GENCAREGROUP = cg.Id
	LEFT join STAT ON STAT.CODCONCEC = A.CODCONCEC
	LEFT JOIN MEDICAMENTOS M ON M.CODCONCEC = A.CODCONCEC
	LEFT JOIN INSUMOS I ON I.CODCONCEC = A.CODCONCEC
	LEFT JOIN MEDICAMENTOS_INSUMOS MI ON MI.CODCONCEC = A.CODCONCEC
	WHERE   (A.ORDESTADO = '1' AND ISNULL(A.ORDENQUIMIO, 0) = 0  AND A.IDAGEPROGQX IS NULL AND (ING.IESTADOIN NOT IN('F','C') OR A.TIPOSOLICITUD = 2  ))
	union

	SELECT	A.CODCONCEC,
			A.CODCONCEP,
			A.CODCONCES,
			A.FECHAORDE, 
			A.CODCENATE, 
			A.UFUCODIGO,
			A.CODCENCOS,
			A.IPCODPACI,
			CAST(ING.NUMINGRES AS CHAR(10))	NUMINGRES,
			A.NUMEFOLIO,
			A.IDETIPHIS,
			CASE WHEN A.MedicalOrderType = 2 THEN '3' -- en caso de que sea PRN
			WHEN A.MedicalOrderType =1 AND ISNULL(STAT.Stat,0)=1 THEN '4' -- En caso de que sea inmediatamente
			WHEN A.ORDTRANUE=3 THEN '5'
			ELSE A.ORDTRANUE 
			END AS ORDTRANUE,
			ISNULL(A.TIPOSOLICITUD, 1) TIPOSOLICITUD,
			A.MEDICAMENTOVALIDADO,
			A.CODBODEGA,
			A.CODPROSAL,
			ADIN.CODCAMACT CODCAMACT,
			A.ORDESTADO,
			ISNULL(cg.ExtramuralPharmaceuticalDispensing,0) TIPOSOLICITUD1, 
			Cg.ExtramuralPharmaceuticalDispensing as PERMITEEXTRA,
			ISNULL((select top 1 1
			from dbo.HCFARMEPD hd
			WHERE hd.CODCONCEC =A.CODCONCEC  AND hd.CANPENPRO>0 AND hd.VIEPROCESSED =0
			),0) as HasQuantityRemaining,
			0 as PatientDischarge,
			M.TIPPRODUC AS MEDICAMENTO,
			I.TIPPRODUC AS INSUMOS,
			MI.TIPPRODUC AS MEDICAMENTO_INSUMO
	FROM dbo.HCFARMEPC AS A WITH (NOLOCK)
	JOIN 
	(
		SELECT IPCODPACI, NUMINGRES AS NUMINGRES,CAST(iif(FECHEGRESO IS NULL,0,1) AS BIT) PatientDischarge
		FROM dbo.ADINGRESO WITH(NOLOCK) 
		WHERE TRATAESPECIA = 3 AND IESTADOIN<>'C'
		GROUP BY IPCODPACI,NUMINGRES,FECHEGRESO
	) AS ING ON A.IPCODPACI = ING.IPCODPACI
	inner join ADINGRESO ADIN on ADIN.NUMINGRES = ING.NUMINGRES
	LEFT JOIN Contract.CareGroup cg WITH (NOLOCK) ON ADIN.GENCAREGROUP = cg.Id
	LEFT join STAT ON STAT.CODCONCEC = A.CODCONCEC
	LEFT JOIN MEDICAMENTOS M ON M.CODCONCEC = A.CODCONCEC
	LEFT JOIN INSUMOS I ON I.CODCONCEC = A.CODCONCEC
	LEFT JOIN MEDICAMENTOS_INSUMOS MI ON MI.CODCONCEC = A.CODCONCEC
	WHERE (A.ORDESTADO = '1' AND ISNULL(A.ORDENQUIMIO, 0) = 0 AND A.IDAGEPROGQX IS NULL AND A.TIPOSOLICITUD = 2)