/**** 
SP para listar el detalle para la creación del JSON para las solicitudes de farmacia de quimioterapia para UNIHEALTH
****/
CREATE PROCEDURE [dbo].[SP_ListarDetalleSolicitudFarmaciaQuimioterapia]
(
  @Consecutivo as Int
)
WITH RECOMPILE
AS
BEGIN
	SET NOCOUNT ON;

	SELECT DISTINCT
				IIF(A.PROESTADO = 3, 1, 0) AS 'CANCELADO', '' AS 'OBSERVACION ITEM', M.INSTRUADMINIS AS 'INDICACIONES', '' AS 'COD TIPO MEZCLA', '' AS 'TIPO MEZCLA',A.TIPOREGIS AS 'COD TIPO PEDIDO', CASE A.TIPOREGIS WHEN 1 THEN 'Medicamentos' WHEN 2 THEN 'Materiales e Insumos' WHEN 3 THEN 'Insumos' END AS 'TIPO PEDIDO', IIF(A.Stat=1, 1, 0) AS 'URGENTE',
				IIF(A.DURACIDOS = 'Dosis Unica', 1, 0) AS 'DOSIS UNICA', ISNULL(A.FRECUENCI, 0) AS 'DURACION', A.UNIFRECUE AS 'COD UNIDAD FRECUENCIA', 
				CASE A.UNIFRECUE WHEN 1 THEN 'Minutos' WHEN 2 THEN 'Horas' WHEN 3 THEN 'Dias' WHEN 4 THEN 'Semanas' WHEN 5 THEN 'Mes' END AS 'UNIDAD FRECUENCIA',
				ISNULL(A.VALDURFIJ, 0)  AS 'POSOLOGIA', RTRIM(A.UNIDURFIJ) AS 'COD UNIDAD POSOLOGIA', CASE A.UNIDURFIJ WHEN 1 THEN 'Minutos' WHEN 2 THEN 'Horas' WHEN 3 THEN 'Dias' WHEN 4 THEN 'Semanas' WHEN 5 THEN 'Mes' END AS 'UNIDAD POSOLOGIA',
				RTRIM(A.CODPRODUC) AS 'COD PRODUCTO', RTRIM(F.Name) AS 'PRODUCTO', A.CANPEDPRO AS 'CANTIDAD', iif(A.DOSISPROD = 0 OR A.DOSISPROD IS NULL ,A.CANPEDPRO ,A.DOSISPROD)AS 'CANTIDAD DOSIS', M.CODVIAADM AS 'COD VIA ADMIN', RTRIM(G.DESVIAADM) AS 'VIA ADMIN', 
				0 AS 'MULTIDOSIS', 0 AS 'BOLO', A.DOSISPROD AS 'DOSIS', H.CODUNIMED AS 'COD UNIDAD MEDIDA', H.DESUNIMED AS 'UNIDAD MEDIDA', A.FECINIDOS AS 'FECHA INICIO', NULL AS 'COD PRODUCTO COMPONENTE', NULL AS 'PRODUCTO COMPONENTE', 0 AS 'CANTIDAD COMPONENTE', NULL AS 'COD UNIDAD MEDIDA COMPONENTE', NULL AS 'UNIDAD MEDIDA COMPONENTE'
				, A.Id as 'Id', A.NUMEFOLIO AS 'NUMEFOLIO', A.IDCITA, AG.FECHORAIN AS 'FECHA CITA'
			FROM HCFARMEPD A
				INNER JOIN HCFARMEPC B ON A.CODCONCEC = B.CODCONCEC AND ORDENQUIMIO = 1
				INNER JOIN AGASICITA AG ON A.IDCITA = AG.CODAUTONU
				LEFT JOIN .ehr.HCORDCICLOSD C on AG.IDHCORDCICLOSD = C.ID 
                LEFT JOIN .ehr.HCORDQUIMIO O on O.ID = C.IDHCORDQUIMIO 
                LEFT JOIN .ehr.HCORDMEDICAM M on M.IDHCORDQUIMIO = O.ID  and M.CICLO = C.CICLO  and C.DIA = M.DIA AND M.CODPRODUC = A.CODPRODUC
                --LEFT JOIN .ehr.HCORMEDICAMESQUEMA ME ON ME.IDHCORDQUIMIO = O.ID and ME.SchemesId = O.SchemesId and ME.CICLO = C.CICLO and ME.CODPRODUC = M.CODPRODUC 
                --LEFT JOIN .dbo.IHLISTPRO P on P.CODPRODUC = M.CODPRODUC 
                LEFT JOIN .dbo.HCVIAADMI G ON G.CODVIAADM = M.CODVIAADM 
                LEFT JOIN .dbo.INUNIMEDI H on H.CODUNIMED = M.CODUNIMED
				INNER JOIN INPROFSAL D ON A.CODPROSAL = D.CODPROSAL 
				INNER JOIN Inventory.InventoryProduct F ON A.CODPRODUC = F.Code
				INNER JOIN INUNIFUNC I ON I.UFUCODIGO = A.UFUCODIGO
			WHERE A.CODCONCEC = @Consecutivo AND A.IDCITA is not null AND A.CANPEDPRO > 0
END