	CASE EVIDENCIA44 WHEN '1' THEN 'X' END AS 'cero4', CASE EVIDENCIA44 WHEN '2' THEN 'X' END AS 'uno4', CASE EVIDENCIA44 WHEN '3' THEN 'X' END AS 'dos4',
