

CREATE PROCEDURE [dbo].[SPHC_ATENCIONURGENCIAS_CTE]
(
@CENTROATENCION CHAR(10),
@USUARIO CHAR(20),
@UFUNCIONAL CHAR(20)
)
AS
BEGIN
	SET NOCOUNT ON;

--NECESITAMOS SABER SI LA UNIDAD QUE ESTA HACIENDO LA CONSULTA ES DE ATENCIÓN PRIORITARIA O URGENCIAS
DECLARE @ATENCIONPRIORITARIA BIT = (SELECT CASE UFUTIPUNI WHEN 31 THEN 1 ELSE 0 END FROM INUNIFUNC WITH (NOLOCK) WHERE UFUCODIGO = @UFUNCIONAL)
DECLARE @ESTADO_3 AS INT = 3
DECLARE @ESTADO_4 AS INT = 4
DECLARE @FECHAINICIOCARGUE DATE = '01/01/2021' 

IF @ATENCIONPRIORITARIA=1 
BEGIN 

;WITH ADINGRESO_NO_ANULADO
AS
(
SELECT UFUCODIGO, CODTIPPAC AS TIPO, RTRIM(IPCODPACI) AS IDENTIFICACION, VIVESOLO, NUMINGRES, IESTADOIN, CODCENATE, IPCODPACI, IFECHAING, CODTIPPAC FROM DBO.ADINGRESO 
WHERE CAST(IFECHAING AS DATE)>@FECHAINICIOCARGUE AND IESTADOIN <> 'A' AND UFUEGRMED IS NULL AND NUMINGRES IS NOT NULL  
AND CODCENATE=@CENTROATENCION AND UFUCODIGO = @UFUNCIONAL
)

,ADINGRESO_ABIERTO
AS
(
SELECT UFUCODIGO, CODTIPPAC AS TIPO, RTRIM(IPCODPACI) AS IDENTIFICACION, VIVESOLO, NUMINGRES, IESTADOIN, CODCENATE, IPCODPACI, IFECHAING, CODTIPPAC FROM DBO.ADINGRESO 
WHERE CAST(IFECHAING AS DATE)>@FECHAINICIOCARGUE AND IESTADOIN = ' ' AND UFUEGRMED IS NULL AND (REQTRIAGE = 0 OR REQTRIAGE IS NULL) 
AND CODCENATE=@CENTROATENCION AND UFUCODIGO = @UFUNCIONAL
)	

,POBESPECIAL
AS
(
SELECT COUNT(*) POBESPECIAL, IPCODPACI FROM DBO.ADPOBESPEPAC Z WITH(NOLOCK) 
INNER JOIN ADPOBESPE X WITH(NOLOCK) ON X.ID = Z.IDADPOBESPE 
WHERE TIPOPOESPERIES = 1
GROUP BY IPCODPACI
)

,ACOMPANANTES
AS
(
SELECT COUNT(*) ACOMPANANTES, NUMINGRES, IPCODPACI FROM ADACOMPAN WITH(NOLOCK) 
GROUP BY NUMINGRES, IPCODPACI
)

,INGRESO_AMBORDIMA
AS
(
SELECT DISTINCT A.NUMINGRES FROM  ADINGRESO AS A WITH(NOLOCK) INNER JOIN AMBORDIMA AS B WITH(NOLOCK) ON B.IPCODPACI = A.IPCODPACI
WHERE  CONVERT(VARCHAR(10),CONVERT(DATE,A.IFECHAING,106),103) = CONVERT(VARCHAR(10),CONVERT(DATE,B.FECORDMED,106),103)
) 

, HC_HISPACA
AS
(
SELECT COUNT(ID) CONTEO, NUMINGRES FROM HCHISPACA WITH(NOLOCK) 
GROUP BY NUMINGRES
)

, DOCUMENTO_BLOQUEADO
AS
(
SELECT NUMDOCUME FROM DBO.INDOCUMEN WITH(NOLOCK) WHERE CODDOCUME=@ESTADO_3 AND CODUSUARI<>@USUARIO
)

, ATENCION_URGENCIAS
AS (
SELECT 	A.TRIAFECHA AS FECHALLEGADA, K.UFUCODIGO,A.TRIORIGEN,CASE A.TRIORIGEN WHEN 1  THEN '1 - PACIENTES MEDICINA GENERAL' WHEN 2 THEN '2 - PACIENTES MEDICINA ESPECIALIZADA' END AS ORIGEN,
		K.CODTIPPAC AS TIPO, TRIANUMER AS CONSECUTIVO,RTRIM(TRIANOMCA) AS [DX SINDROMATICO],RTRIM(K.IPCODPACI) AS IDENTIFICACION, RTRIM(F.IPNOMCOMP) AS [NOMBRE PACIENTE], TRIAFECHA AS [FECHA TRIAGE],0 AS MINUTOS,0 AS BARRA,CAST(0 AS BIT) AS CONFIRMADO,CAST(0 AS BIT) AS AUSENTE,A.NUMINGRES AS INGRESO,IPFECNACI AS 'FECHA NACIMIENTO' ,CAST('' AS CHAR(50)) AS EDAD,RTRIM(G.DESESPECI) AS ESPECIALIDAD
		, CASE WHEN F.IPTIPODOC IN(6,7) THEN 1 ELSE 0 END AS ASMS
		, F.ZONAPARTADA,
		L.RIESGOAGRE,
		PE.POBESPECIAL, --(SELECT COUNT(*) FROM DBO.ADPOBESPEPAC Z WITH(NOLOCK) INNER JOIN ADPOBESPE X WITH(NOLOCK) ON X.ID = Z.IDADPOBESPE WHERE IPCODPACI = F.IPCODPACI AND TIPOPOESPERIES = 1) AS POBESPECIAL,
		K.VIVESOLO,
		AC.ACOMPANANTES,   --(SELECT COUNT(*) FROM ADACOMPAN WITH(NOLOCK) WHERE NUMINGRES = K.NUMINGRES) AS ACOMPANANTES,
		CONVERT(BIT,0) AS RIESGO, RTRIM(F.CODENTIDA) + '-'+ RTRIM(M.NOMENTIDA) AS ENTIDADPACIENTE
		FROM DBO.ADTRIAGEU A WITH(NOLOCK) 
		LEFT JOIN ADINGRESO_NO_ANULADO K WITH(NOLOCK) ON A.NUMINGRES = K.NUMINGRES LEFT JOIN INGRESO_AMBORDIMA AM WITH(NOLOCK) ON K.NUMINGRES=AM.NUMINGRES AND AM.NUMINGRES IS NULL --AND K.NUMINGRES NOT IN (SELECT DISTINCT A.NUMINGRES FROM  ADINGRESO AS A WITH(NOLOCK) INNER JOIN AMBORDIMA AS B WITH(NOLOCK) ON B.IPCODPACI = A.IPCODPACI WHERE  CONVERT(VARCHAR(10),CONVERT(DATE,A.IFECHAING,106),103) = CONVERT(VARCHAR(10),CONVERT(DATE,B.FECORDMED,106),103)) 
		--INNER JOIN DBO.INPROFSAL D WITH(NOLOCK) ON D.CODPROSAL=A.CODPROSAL 
		INNER JOIN DBO.ADCATTRIU E WITH(NOLOCK) ON E.TRIACATEG=A.TRIACATEG 
		INNER JOIN DBO.INPACIENT F WITH(NOLOCK) ON K.IPCODPACI=F.IPCODPACI 
	    LEFT JOIN DBO.INESPECIA G WITH(NOLOCK) ON A.CODESPECI=G.CODESPECI 
		LEFT JOIN DBO.ADACTIVID L WITH(NOLOCK) ON F.CODACTIVI = L.CODACTIVI 
		LEFT JOIN DBO.INENTIDAD M WITH(NOLOCK) ON M.CODENTIDA = F.CODENTIDA 
		LEFT JOIN HC_HISPACA HC WITH(NOLOCK) ON K.NUMINGRES =HC.NUMINGRES AND CONTEO=0 --AND (SELECT COUNT(ID) FROM HCHISPACA WITH(NOLOCK) WHERE NUMINGRES = K.NUMINGRES) = 0 
		LEFT JOIN DOCUMENTO_BLOQUEADO DOC WITH(NOLOCK) ON K.IPCODPACI=DOC.NUMDOCUME AND DOC.NUMDOCUME IS NULL
		LEFT JOIN POBESPECIAL PE WITH(NOLOCK) ON K.IPCODPACI=PE.IPCODPACI
		LEFT JOIN ACOMPANANTES AC WITH(NOLOCK) ON K.IPCODPACI=AC.IPCODPACI
		--WHERE 
		--K.UFUEGRMED IS NULL 
		/* K.IFECHAING > '21/10/2016' VALIDACIÓN PARA MEDILASER DEBIDO QUE SE LE ESTABA MOSTRANDO MUCHOS PACIENTES*/
		--AND K.IFECHAING > @FECHAINICIOCARGUE 
		--AND K.IESTADOIN <> @IESTADOIN_ANULADO 
		--AND K.NUMINGRES NOT IN (SELECT DISTINCT A.NUMINGRES FROM  ADINGRESO AS A WITH(NOLOCK) INNER JOIN AMBORDIMA AS B WITH(NOLOCK) ON B.IPCODPACI = A.IPCODPACI WHERE  CONVERT(VARCHAR(10),CONVERT(DATE,A.IFECHAING,106),103) = CONVERT(VARCHAR(10),CONVERT(DATE,B.FECORDMED,106),103)) 
		--AND (SELECT COUNT(ID) FROM HCHISPACA WITH(NOLOCK) WHERE NUMINGRES = K.NUMINGRES) = 0 
		--AND K.CODCENATE = @CENTROATENCION 
		--AND K.UFUCODIGO = @UFUNCIONAL
		--AND K.NUMINGRES IS NOT NULL 
		--AND K.NUMINGRES NOT IN (SELECT NUMDOCUME FROM DBO.INDOCUMEN WITH(NOLOCK) WHERE CODDOCUME=@ESTADO_3 AND CODUSUARI<>@USUARIO) 

					UNION
	
					SELECT 
					K.IFECHAING AS FECHALLEGADA, K.UFUCODIGO,0 AS TRIORIGEN,	'3 - PACIENTES SIN CLASIFICACIÓN DE TRIAGE' AS ORIGEN,
					K.CODTIPPAC AS TIPO, 0 AS CONSECUTIVO,
					'' AS [DX SINDROMATICO],RTRIM(K.IPCODPACI) AS IDENTIFICACION,RTRIM(F.IPNOMCOMP) AS [NOMBRE PACIENTE], 
					K.IFECHAING AS [FECHA TRIAGE],0 AS MINUTOS,0 AS BARRA,CAST(0 AS BIT) AS CONFIRMADO,CAST(0 AS BIT) AS AUSENTE,K.NUMINGRES AS INGRESO,
					IPFECNACI AS 'FECHA NACIMIENTO' ,CAST('' AS CHAR(50)) AS EDAD,'' AS ESPECIALIDAD
					, CASE WHEN F.IPTIPODOC IN(6,7) THEN 1 ELSE 0 END AS ASMS
					, F.ZONAPARTADA,
					L.RIESGOAGRE,
					PE.POBESPECIAL, --(SELECT COUNT(*) FROM DBO.ADPOBESPEPAC Z WITH(NOLOCK) INNER JOIN ADPOBESPE X WITH(NOLOCK) ON X.ID = Z.IDADPOBESPE WHERE IPCODPACI = F.IPCODPACI AND TIPOPOESPERIES = 1) AS POBESPECIAL,
					K.VIVESOLO,
					AC.ACOMPANANTES,   --(SELECT COUNT(*) FROM ADACOMPAN WITH(NOLOCK) WHERE NUMINGRES = K.NUMINGRES) AS ACOMPANANTES,
					CONVERT(BIT,0) AS RIESGO, RTRIM(F.CODENTIDA) + '-'+ RTRIM(M.NOMENTIDA) AS ENTIDADPACIENTE
					FROM ADINGRESO_ABIERTO K WITH(NOLOCK) LEFT JOIN INGRESO_AMBORDIMA AM WITH(NOLOCK) ON K.NUMINGRES=AM.NUMINGRES AND AM.NUMINGRES IS NULL --AND K.NUMINGRES NOT IN (SELECT DISTINCT A.NUMINGRES FROM  ADINGRESO AS A WITH(NOLOCK) INNER JOIN AMBORDIMA AS B WITH(NOLOCK) ON B.IPCODPACI = A.IPCODPACI WHERE  CONVERT(VARCHAR(10),CONVERT(DATE,A.IFECHAING,106),103) = CONVERT(VARCHAR(10),CONVERT(DATE,B.FECORDMED,106),103)) 
					INNER JOIN DBO.INPACIENT F WITH(NOLOCK) ON K.IPCODPACI=F.IPCODPACI 
					LEFT JOIN DBO.ADACTIVID L WITH(NOLOCK) ON F.CODACTIVI = L.CODACTIVI 
					LEFT JOIN DBO.INENTIDAD M WITH(NOLOCK) ON M.CODENTIDA = F.CODENTIDA
					LEFT JOIN DOCUMENTO_BLOQUEADO DOC WITH(NOLOCK) ON K.IPCODPACI=DOC.NUMDOCUME AND DOC.NUMDOCUME IS NULL
					LEFT JOIN POBESPECIAL PE WITH(NOLOCK) ON K.IPCODPACI=PE.IPCODPACI
					LEFT JOIN ACOMPANANTES AC WITH(NOLOCK) ON K.IPCODPACI=AC.IPCODPACI
					LEFT JOIN HC_HISPACA HC WITH(NOLOCK) ON K.NUMINGRES =HC.NUMINGRES AND CONTEO=0 
					/* K.IFECHAING > '21/10/2016' VALIDACIÓN PARA MEDILASER DEBIDO QUE SE LE ESTABA MOSTRANDO MUCHOS PACIENTES*/
					--WHERE  K.UFUEGRMED IS NULL 
					--AND K.IFECHAING > @FECHAINICIOCARGUE 
					--AND K.IESTADOIN = @IESTADOIN_ABIERTO 
					--AND K.NUMINGRES NOT IN (SELECT DISTINCT A.NUMINGRES FROM  ADINGRESO AS A WITH(NOLOCK) INNER JOIN AMBORDIMA AS B WITH(NOLOCK) ON B.IPCODPACI = A.IPCODPACI WHERE  CONVERT(VARCHAR(10),CONVERT(DATE,A.IFECHAING,106),103) = CONVERT(VARCHAR(10),CONVERT(DATE,B.FECORDMED,106),103))
					--AND (K.REQTRIAGE = 0 OR K.REQTRIAGE IS NULL) 
					--AND (SELECT COUNT(ID) FROM HCHISPACA WITH(NOLOCK) WHERE NUMINGRES = K.NUMINGRES) = 0 
					--AND K.CODCENATE = @CENTROATENCION
					--AND K.UFUCODIGO = @UFUNCIONAL 
					--AND K.NUMINGRES NOT IN (SELECT NUMDOCUME FROM DBO.INDOCUMEN WITH(NOLOCK) WHERE CODDOCUME=@ESTADO_3 AND CODUSUARI<>@USUARIO) 
) 
SELECT * FROM ATENCION_URGENCIAS ORDER BY [FECHA TRIAGE]
END

ELSE BEGIN

; WITH POBESPECIAL
AS
(
SELECT COUNT(*) POBESPECIAL, IPCODPACI FROM DBO.ADPOBESPEPAC Z WITH(NOLOCK) 
INNER JOIN ADPOBESPE X WITH(NOLOCK) ON X.ID = Z.IDADPOBESPE 
WHERE TIPOPOESPERIES = 1
GROUP BY IPCODPACI
)

,ACOMPANANTES
AS
(
SELECT COUNT(*) ACOMPANANTES, NUMINGRES, IPCODPACI FROM ADACOMPAN WITH(NOLOCK) 
GROUP BY NUMINGRES, IPCODPACI
)

, DOCUMENTO_BLOQUEADO
AS
(
SELECT NUMDOCUME FROM DBO.INDOCUMEN WITH(NOLOCK) WHERE CODDOCUME=@ESTADO_3 AND CODUSUARI<>@USUARIO
)

, HC_HISPACA
AS
(
SELECT COUNT(ID) CONTEO, NUMINGRES FROM HCHISPACA WITH(NOLOCK) 
GROUP BY NUMINGRES
)

,CLASIFICADO_CON_INGRESO
AS
(
		SELECT 
			B.UFUCODIGO,A.TRIORIGEN,CASE A.TRIORIGEN WHEN 1  THEN '1 - PACIENTES MEDICINA GENERAL' WHEN 2 THEN '2 - PACIENTES MEDICINA ESPECIALIZADA' END AS ORIGEN,K.CODTIPPAC AS TIPO, TRIANUMER AS CONSECUTIVO,RTRIM(TRIANOMCA) AS [DX SINDROMATICO],RTRIM(B.IPCODPACI) AS IDENTIFICACION,RTRIM(F.IPNOMCOMP) AS [NOMBRE PACIENTE], TRIAFECHA AS [FECHA TRIAGE],0 AS MINUTOS,0 AS BARRA,CASE CAST(TRIAGECLA AS CHAR) WHEN '1' THEN '1 - REANIMACIÓN' WHEN '2' THEN '2 - EMERGENCIA' WHEN '3' THEN '3 - URGENCIA MÉDICA' WHEN '4' THEN '4 - URGENCIA DIFERIDA' WHEN '5' THEN '5 - NO URGENTE' END AS TRIAGE,CAST(0 AS BIT) AS CONFIRMADO,CAST(0 AS BIT) AS AUSENTE,A.NUMINGRES AS INGRESO,IPFECNACI AS 'FECHA NACIMIENTO' ,CAST('' AS CHAR(50)) AS EDAD,RTRIM(G.DESESPECI) AS ESPECIALIDAD
			, CASE WHEN F.IPTIPODOC IN(6,7) THEN 1 ELSE 0 END AS ASMS
			, F.ZONAPARTADA,
			L.RIESGOAGRE,
			PE.POBESPECIAL,--(SELECT COUNT(*) FROM DBO.ADPOBESPEPAC Z WITH(NOLOCK) INNER JOIN ADPOBESPE X WITH(NOLOCK) ON X.ID = Z.IDADPOBESPE WHERE IPCODPACI = F.IPCODPACI AND TIPOPOESPERIES = 1) AS POBESPECIAL,
			K.VIVESOLO,
			AC.ACOMPANANTES,--(SELECT COUNT(*) FROM ADACOMPAN WITH(NOLOCK) WHERE NUMINGRES = K.NUMINGRES) AS ACOMPANANTES,
			CONVERT(BIT,0) AS RIESGO, RTRIM(F.CODENTIDA) + '-'+ RTRIM(M.NOMENTIDA) AS ENTIDADPACIENTE
		FROM 
			DBO.ADTRIAGEU A WITH(NOLOCK) 
			INNER JOIN DBO.ADINGRESO K WITH(NOLOCK) ON A.NUMINGRES = K.NUMINGRES AND A.NUMINGRES IS NOT NULL AND A.CODCENATE = @CENTROATENCION 
            INNER JOIN DBO.ADCONTURG B WITH(NOLOCK) ON A.CODCONCEC=B.CODCONCEC AND B.CONESTADO = @ESTADO_4  
			--INNER JOIN DBO.INPROFSAL D WITH(NOLOCK) ON D.CODPROSAL=A.CODPROSAL 
			INNER JOIN DBO.ADCATTRIU E WITH(NOLOCK) ON E.TRIACATEG=A.TRIACATEG 
			INNER JOIN DBO.INPACIENT F WITH(NOLOCK) ON B.IPCODPACI=F.IPCODPACI 
			LEFT JOIN DBO.INESPECIA G WITH(NOLOCK) ON A.CODESPECI=G.CODESPECI 
			LEFT JOIN DBO.ADACTIVID L WITH(NOLOCK) ON F.CODACTIVI = L.CODACTIVI 
			LEFT JOIN DBO.INENTIDAD M WITH(NOLOCK) ON M.CODENTIDA = F.CODENTIDA 
			LEFT JOIN DOCUMENTO_BLOQUEADO DOC WITH(NOLOCK) ON K.IPCODPACI=DOC.NUMDOCUME AND DOC.NUMDOCUME IS NULL --AND A.NUMINGRES NOT IN (SELECT NUMDOCUME FROM DBO.INDOCUMEN WITH(NOLOCK) WHERE CODDOCUME=@ESTADO_3 AND CODUSUARI<>@USUARIO)  
			LEFT JOIN POBESPECIAL PE WITH(NOLOCK) ON K.IPCODPACI=PE.IPCODPACI
			LEFT JOIN ACOMPANANTES AC WITH(NOLOCK) ON K.IPCODPACI=AC.IPCODPACI
			LEFT JOIN HC_HISPACA HC WITH(NOLOCK) ON K.NUMINGRES =HC.NUMINGRES AND CONTEO=0
		 WHERE B.CONESTADO = @ESTADO_4 
			AND K.UFUCODIGO = @UFUNCIONAL
			--AND A.NUMINGRES NOT IN (SELECT NUMDOCUME FROM DBO.INDOCUMEN WITH(NOLOCK) WHERE CODDOCUME=@ESTADO_3 AND CODUSUARI<>@USUARIO)  
			--ORDER BY TRIAGECLA
 )

SELECT * FROM CLASIFICADO_CON_INGRESO ORDER BY [FECHA TRIAGE]
END

END