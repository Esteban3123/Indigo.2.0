);


GO
CREATE NONCLUSTERED INDEX [IX_INTIMAGEN__ORDEN_INDIGO__CODSERIPS__INC__DESIMGLAB__IMAGENLAB]
    ON [dbo].[INTIMAGEN]([ORDEN_INDIGO] ASC, [CODSERIPS] ASC)
