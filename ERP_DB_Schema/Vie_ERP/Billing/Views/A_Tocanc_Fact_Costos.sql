









CREATE view [Billing].[A_Tocanc_Fact_Costos]
AS

SELECT       RTRIM(CEN.NOMCENATE) AS CENTRO_ATENCION, BILLING.REVENUECONTROLDETAIL.CAREGROUPID, BILLING.REVENUECONTROLDETAIL.ID, ING.IESTADOIN AS ESTADO_INGRESO, SO.ADMISSIONNUMBER AS INGRESO, ING.IFECHAING AS FECHA_INGRESO, 
                         BILLING.REVENUECONTROL.PATIENTCODE AS IDENTIFICACIÓN, P.IPNOMCOMP AS PACIENTE, P.IPFECNACI AS FECHA_NACIMIENTO, 
						 DATEDIFF(YEAR,P.IPFECNACI,ING.IFECHAING) AS EDAD_EN_CONSULTA , 
						 T .NAME AS ENTIDAD, BILLING.REVENUECONTROLDETAIL.FOLIOORDER AS FOLIOS_A_FACTURAR, 
                         CASE BILLING.REVENUECONTROLDETAIL.FOLIOTYPE WHEN '1' THEN 'EAPB CON CONTRATO' WHEN '2' THEN 'EAPB SIN CONTRATO' WHEN '3' THEN 'PARTICULARES' WHEN '4' THEN 'ASEGURADORAS' END AS TIPO, 
                         CASE BILLING.REVENUECONTROLDETAIL.LIQUIDATIONTYPE WHEN '1' THEN 'PAGO POR SERVICIOS' WHEN '2' THEN 'CAPITACION' WHEN '3' THEN 'FACTURA GLOBAL' WHEN '4' THEN 'CAPITACION GLOBAL' END AS TIPO_LIQUIDACION,
                          EA.HEALTHENTITYCODE AS ENTIDAD_ADMINISTRADORA, T .NIT AS NIT_ENTIDAD, GA.CODE AS GRUPO_ATENCIÓN, GA.NAME AS DESCRIPCIÓN_GRUPO_ATENCIÓN, 
                         BILLING.REVENUECONTROLDETAIL.TOTALFOLIO AS [VR TOTAL FOLIO PENDIENTE FACTURAR], DQ.INVOICEDQUANTITY AS [CANTIDAD QX], DQ.TOTALSALESPRICE AS [TOTAL FACTURADO QX], 
                         DQ.PERFORMSHEALTHPROFESSIONALCODE AS [CÓD PROFESIONAL QX], RTRIM(MEDQX.CODPROSAL) + ' - ' + LTRIM(MEDQX.NOMMEDICO) AS [PROFESIONAL QX], 
                         CASE BILLING.REVENUECONTROLDETAIL.RESPONSIBLERECOVERYFEE WHEN '1' THEN 'NINGUNO' WHEN '2' THEN 'PACIENTE' WHEN '3' THEN 'TERCERO' END AS [RESPONSABLE CUOTA RECUPERACIÓN], 
						 CASE P.TIPCOBSAL
						 WHEN '1' THEN 'CONTRIBUTIVO'
					     WHEN '2' THEN 'SUBSIDIADO TOTAL'
					     WHEN '3' THEN 'SUBSIDIADO PARCIAL'
					     WHEN '4' THEN 'POBLACION POBRE SIN ASEGURAR CON SISBEN'
					     WHEN '5' THEN 'POBLACION POBRE SIN ASEGURAR SIN SISBEN'
					     WHEN '6' THEN 'DESPLAZADOS'
					     WHEN '7' THEN 'PLAN DE SALUD ADICIONAL'
					     WHEN '8' THEN 'OTROS'
						 ELSE 'DESCONOCIDO' END AS TIPO_PACIENTE,
                         BILLING.REVENUECONTROLDETAIL.TOTALPATIENTWITHDISCOUNT AS [VR COBRADO A PACIENTE], BILLING.REVENUECONTROLDETAIL.VALUECOPAY AS [VR CUOTA RECUPERACIÓN FOLIO], 
                         BILLING.REVENUECONTROLDETAIL.VALUEFEEMODERATOR AS [VR CUOTA MODERADORA FOLIO], BILLING.REVENUECONTROLDETAIL.OBSERVATION AS [OBSERVACIONES], CAT.NAME AS [CATEGORÍA PARA RIPS], 
                         CASE BILLING.REVENUECONTROLDETAIL.STATUS WHEN '1' THEN 'REGISTRADO' WHEN '2' THEN 'FACTURADO' WHEN '3' THEN 'BLOQUEADO' END AS 'ESTADO', --PER.FULLNAME AS [USUARIO CREA], 
                         BILLING.REVENUECONTROLDETAIL.CREATIONDATE AS [FECHA CREACIÓN], ---PERM .FULLNAME AS [USUARIO MODIFICA], 
						 BILLING.REVENUECONTROLDETAIL.MODIFICATIONDATE AS [FECHA MODIFICACIÓN], 
                         CASE BILLING.SERVICEORDERDETAIL.SERVICETYPE WHEN '1' THEN 'SOAT' WHEN '2' THEN 'ISS' WHEN '3' THEN 'CUPS' END AS [TIPO SERVICIO], 
                         CASE BILLING.SERVICEORDERDETAIL.RECORDTYPE WHEN '1' THEN 'SERVICIOS' WHEN '2' THEN 'MEDICAMENTOS' END AS [SERVICIOS/MEDICAMENTOS], CUPS.CODE AS [CÓDIGO CUPS], 
                         CUPS.DESCRIPTION AS [DESCRIPCIÓN CUPS], SERVICIOSIPS.CODE AS [CÓDIGO SERVICIO], SERVICIOSIPS.NAME AS [DESCRIPCIÓN SERVICIO], BILLING.SERVICEORDERDETAIL.PACKAGING AS [SERVICIO INCLUIDO EN PAQUETE], 
                         CASE BILLING.SERVICEORDERDETAIL.PRESENTATION WHEN '1' THEN 'NO QUIRÚRGICO' WHEN '2' THEN 'QUIRÚRGICO' WHEN '3' THEN 'PAQUETE' END AS [PRESENTACIÓN SERVICIO], PR.CODE AS [CÓD PRODUCTO], 
                         PR.NAME AS [DESCRIPCIÓN PRODUCTO], BILLING.SERVICEORDERDETAIL.SUPPLYQUANTITY AS [CANTIDAD ENTREGADA], BILLING.SERVICEORDERDETAIL.DEVOLUTIONQUANTITY AS [CANTIDAD DEVUELTA], 
                         BILLING.SERVICEORDERDETAIL.INVOICEDQUANTITY AS [CANTIDAD A FACTURAR], BILLING.SERVICEORDERDETAIL.RATEMANUALSALEPRICE AS [VALOR UNITARIO  A FACTURAR ], (BILLING.SERVICEORDERDETAIL.INVOICEDQUANTITY) 
                         * (BILLING.SERVICEORDERDETAIL.RATEMANUALSALEPRICE) AS [TOTAL A FACTURAR], BILLING.REVENUECONTROLDETAIL.TOTALPATIENTSALESPRICE AS [TOTAL CUOTA RECUPERACIÓN], 
                         BILLING.SERVICEORDERDETAIL.SERVICEDATE AS [FECHA SERVICIO], BILLING.SERVICEORDERDETAIL.AUTHORIZATIONNUMBER AS [AUTORIZACIÓN], UF.CODE AS CODIGO_UNIDAD_FUNCIONAL_INGRESO, 
                         UF.NAME AS UNIDAD_FUNCIONAL_INGRESO, SALIDA.FECALTPAC AS FECHA_ALTA_MEDICA, 
						 YEAR(SALIDA.FECALTPAC) AS  AÑO_FECHA_ALTA_MEDICA,
						 MONTH(SALIDA.FECALTPAC) AS MES_FECHA_ALTA_MEDICA,
						 DAY(SALIDA.FECALTPAC) AS  DIA_FECHA_ALTA_MEDICA,
						 CASE MONTH(SALIDA.FECALTPAC)
							WHEN 1 THEN 'ENERO'
							WHEN 2 THEN 'FEBRERO'
							WHEN 3 THEN 'MARZO'
							WHEN 4 THEN 'ABRIL'
							WHEN 5 THEN 'MAYO'
							WHEN 6 THEN 'JUNIO'
							WHEN 7 THEN 'JULIO'
							WHEN 8 THEN 'AGOSTO'
							WHEN 9 THEN 'SEPTIEMBRE'
							WHEN 10 THEN 'OCTUBRE'
							WHEN 11 THEN 'NOVIEMBRE'
							WHEN 12 THEN 'DICIEMBRE'
							ELSE 'DESCONOCIDO'
						 END MES_NOMBRE_FECHA_ALTA_MEDICA,
						 YEAR(ING.IFECHAING) AS  AÑO_FECHA_INGRESO,
						 MONTH(ING.IFECHAING) AS MES_FECHA_INGRESO,
						 DAY(ING.IFECHAING) AS  DIA_FECHA_INGRESO,
						 CASE MONTH(ING.IFECHAING)
							WHEN 1 THEN 'ENERO'
							WHEN 2 THEN 'FEBRERO'
							WHEN 3 THEN 'MARZO'
							WHEN 4 THEN 'ABRIL'
							WHEN 5 THEN 'MAYO'
							WHEN 6 THEN 'JUNIO'
							WHEN 7 THEN 'JULIO'
							WHEN 8 THEN 'AGOSTO'
							WHEN 9 THEN 'SEPTIEMBRE'
							WHEN 10 THEN 'OCTUBRE'
							WHEN 11 THEN 'NOVIEMBRE'
							WHEN 12 THEN 'DICIEMBRE'
							ELSE 'DESCONOCIDO'
						 END MES_NOMBRE_FECHA_INGRESO,
						  CASE WHEN SALIDA.FECALTPAC IS NULL THEN 'SIN ALTA MÉDICA'
                          ELSE 'CON ALTA MÉDICA' END AS 'INGRESO_ALTA_MEDICA',
						 --BILLING.REVENUECONTROLDETAIL.TIMESTAMP, 
						 ING.UFUEGRMED AS CODIGO_UNIDAD_FUNCIONAL_EGRESO, UFE.UFUDESCRI AS UNIDAD_FUNCIONAL_EGRESO, CAMA.DESCCAMAS AS CAMA_EGRESO,
						CASE  CEN.NOMCENATE WHEN 'CLINICA DE ALTA TECNOLOGIA MARAYA' THEN '4.812775'
						 WHEN 'CIRCUNVALAR' THEN '4.808665'
						 WHEN 'SAN MARCEL' THEN '5.036220'
						 WHEN 'HOSPITALIZACION INFANTIL' THEN '5.064226'
						 WHEN 'CENTENARIO' THEN '4.542379'
						 WHEN 'SAN JUAN DE DIOS' THEN '4.557683'
						 WHEN 'CLINICA ARTURO LOPEZ CARDONA' THEN '4.545148'
						 WHEN 'CARTAGO UNIDAD ONCOLOGICA' THEN '4.754317'
						 END UBICACION_LATITUD,
						CASE  CEN.NOMCENATE WHEN 'CLINICA DE ALTA TECNOLOGIA MARAYA' THEN '-75.721576'
						 WHEN 'CIRCUNVALAR' THEN '-75.680038'
						 WHEN 'SAN MARCEL' THEN '-75.469270'
						 WHEN 'HOSPITALIZACION INFANTIL' THEN '-75.498604'
						 WHEN 'CENTENARIO' THEN '-75.658726'
						 WHEN 'SAN JUAN DE DIOS' THEN '-75.656878'
						 WHEN 'CLINICA ARTURO LOPEZ CARDONA' THEN '-75.661106'
						 WHEN 'CARTAGO UNIDAD ONCOLOGICA' THEN '-75.926218'
						 END UBICACION_LONGITUD
--INTO [PBI].[STG_PENDIENTE_FACTURACION]
FROM            BILLING.REVENUECONTROLDETAIL WITH (NOLOCK) INNER JOIN
                         BILLING.SERVICEORDERDETAILDISTRIBUTION WITH (NOLOCK) ON BILLING.REVENUECONTROLDETAIL.ID = BILLING.SERVICEORDERDETAILDISTRIBUTION.REVENUECONTROLDETAILID AND 
                         BILLING.REVENUECONTROLDETAIL.STATUS IN ('1', '3') INNER JOIN
                         BILLING.SERVICEORDERDETAIL WITH (NOLOCK) ON BILLING.SERVICEORDERDETAILDISTRIBUTION.SERVICEORDERDETAILID = BILLING.SERVICEORDERDETAIL.ID INNER JOIN
                         BILLING.REVENUECONTROL WITH (NOLOCK) ON BILLING.REVENUECONTROLDETAIL.REVENUECONTROLID = BILLING.REVENUECONTROL.ID LEFT  JOIN
                         DBO.INPACIENT AS P WITH (NOLOCK) ON P.IPCODPACI = BILLING.REVENUECONTROL.PATIENTCODE LEFT  JOIN
                         CONTRACT.CONTRACTENTITY AS E WITH (NOLOCK) ON E.ID = BILLING.REVENUECONTROLDETAIL.CONTRACTENTITYID LEFT  JOIN
                         CONTRACT.CAREGROUP AS GA WITH (NOLOCK) ON GA.ID = BILLING.REVENUECONTROLDETAIL.CAREGROUPID LEFT  JOIN
                         BILLING.INVOICECATEGORIES AS CAT WITH (NOLOCK) ON CAT.ID = BILLING.REVENUECONTROLDETAIL.INVOICECATEGORYID LEFT  JOIN
                         --INDIGOSEC.SECURITY.[USER] AS U WITH (NOLOCK) ON U.USERCODE = BILLING.REVENUECONTROLDETAIL.CREATIONUSER LEFT  JOIN
                         --INDIGOSEC.SECURITY.PERSON AS PER WITH (NOLOCK) ON PER.ID = U.IDPERSON LEFT  JOIN
                         --INDIGOSEC.SECURITY.[USER] AS UM WITH (NOLOCK) ON UM.USERCODE = BILLING.REVENUECONTROLDETAIL.MODIFICATIONUSER LEFT  JOIN
                         --INDIGOSEC.SECURITY.PERSON AS PERM WITH (NOLOCK) ON PERM .ID = UM.IDPERSON LEFT  JOIN
                         CONTRACT.CUPSENTITY AS CUPS WITH (NOLOCK) ON CUPS.ID = BILLING.SERVICEORDERDETAIL.CUPSENTITYID LEFT  JOIN
                         CONTRACT.IPSSERVICE AS SERVICIOSIPS WITH (NOLOCK) ON SERVICIOSIPS.ID = BILLING.SERVICEORDERDETAIL.IPSSERVICEID LEFT  JOIN
                         INVENTORY.INVENTORYPRODUCT AS PR WITH (NOLOCK) ON PR.ID = BILLING.SERVICEORDERDETAIL.PRODUCTID LEFT  JOIN
                         PAYROLL.FUNCTIONALUNIT AS UF WITH (NOLOCK) ON UF.ID = BILLING.SERVICEORDERDETAIL.PERFORMSFUNCTIONALUNITID LEFT  JOIN
                         DBO.HCREGEGRE AS SALIDA WITH (NOLOCK) ON SALIDA.NUMINGRES = BILLING.REVENUECONTROL.ADMISSIONNUMBER LEFT JOIN
						 DBO.HCREGEST AS CAME WITH (NOLOCK) ON SALIDA.NUMEFOLIO=CAME.NUMEFOLIO AND SALIDA.IPCODPACI=CAME.IPCODPACI AND SALIDA.NUMINGRES=CAME.NUMINGRES  AND SALIDA.UFUCODIGO=CAME.UFUCODIGO LEFT JOIN
						 DBO.CHCAMASHO AS CAMA WITH (NOLOCK) ON CAME.UFUCODIGO=CAMA.UFUCODIGO AND CAME.CODICAMAS = CAMA.CODICAMAS LEFT JOIN
                         CONTRACT.HEALTHADMINISTRATOR AS EA WITH (NOLOCK) ON EA.ID = BILLING.REVENUECONTROLDETAIL.HEALTHADMINISTRATORID LEFT  JOIN
                         COMMON.THIRDPARTY AS T WITH (NOLOCK) ON T .ID = BILLING.SERVICEORDERDETAIL.THIRDPARTYID LEFT  JOIN
                         DBO.ADINGRESO AS ING WITH (NOLOCK) ON ING.NUMINGRES = BILLING.REVENUECONTROL.ADMISSIONNUMBER INNER JOIN
                         .ADCENATEN AS CEN ON CEN.CODCENATE = ING.CODCENATE LEFT  JOIN
						 DBO.INUNIFUNC AS UFE WITH (NOLOCK) ON ING.UFUEGRMED = UFE.UFUCODIGO LEFT  JOIN
                         BILLING.SERVICEORDERDETAILSURGICAL AS DQ WITH (NOLOCK) ON DQ.SERVICEORDERDETAILID = BILLING.SERVICEORDERDETAIL.ID LEFT  JOIN
                         CONTRACT.IPSSERVICE AS SERVICIOSIPSQ WITH (NOLOCK) ON SERVICIOSIPSQ.ID = DQ.IPSSERVICEID LEFT  JOIN
                         DBO.INPROFSAL AS MEDQX WITH (NOLOCK) ON MEDQX.CODPROSAL = DQ.PERFORMSHEALTHPROFESSIONALCODE LEFT  JOIN
                         BILLING.SERVICEORDER AS SO WITH (NOLOCK) ON SO.ID = BILLING.SERVICEORDERDETAIL.SERVICEORDERID 
WHERE        ---BILLING.REVENUECONTROLDETAIL.STATUS IN ('1', '3') 
--AND 
BILLING.SERVICEORDERDETAIL.ISDELETE = '0' AND ING.IESTADOIN <> 'A' 
--AND ING.IESTADOIN <> 'F' 
AND ING.IESTADOIN <> 'C'