


CREATE PROCEDURE [dbo].[SPCH_ListarPacientesEnObservacion]
(
@UnidadFuncional Char(10)
)
AS
BEGIN
	SET NOCOUNT ON;

SELECT DISTINCT 
A.CODTIPPAC as TipoPaciente,
rtrim(c.DESESPECI) as EspecialidadTratante,  cast(' ' as char(100)) AS Origen,'Normal' as Alerta,A.IPCODPACI AS Identificacion,A.NUMINGRES AS Ingreso,RTRIM(B.IPNOMCOMP) AS Paciente,CAST(0 AS BIT) AS Resultado,IFECHAING,CAST('' as bit) AS MuestraAlerta ,INGRECEXT as Remitido,CASE CAST(TRIAGECLA AS CHAR) WHEN 1 THEN 'TRIAGE I' WHEN 2 THEN 'TRIAGE II' WHEN 3 THEN 'TRIAGE III' WHEN 4 THEN 'TRIAGE IV' WHEN 5 THEN 'TRIAGE V' END AS Triage
, CASE WHEN B.IPTIPODOC IN(6,7) THEN 1 ELSE 0 END AS ASMS
, B.ZONAPARTADA,
L.RIESGOAGRE,
(SELECT count(*) FROM dbo.ADPOBESPEPAC Z with(nolock) INNER JOIN ADPOBESPE X with(nolock) ON X.ID = Z.IDADPOBESPE WHERE IPCODPACI = B.IPCODPACI AND TIPOPOESPERIES = 1) AS POBESPECIAL,
A.VIVESOLO,
(SELECT count(*) FROM ADACOMPAN with(nolock) WHERE NUMINGRES = A.NUMINGRES) AS ACOMPANANTES,
CONVERT(BIT,0) AS Riesgo,
isnull(A.DESTINOPAC,0) as Agrupacion,
IPFECNACI AS 'Fecha Nacimiento' ,CAST('' AS CHAR(50)) AS Edad, RTRIM(P.CODENTIDA) + '-'+ RTRIM(P.NOMENTIDA) as EntidadPaciente, RTRIM(Q.CODDIAGNO) + '-' + RTRIM(Q.NOMDIAGNO) as Diagnostico
,(SELECT TOP 1 FECHISPAC FROM HCHISPACA with(nolock) WHERE IPCODPACI = A.IPCODPACI AND NUMINGRES = A.NUMINGRES ORDER BY FECHISPAC DESC) AS FechaHC, 0 AS [Minutos],0 AS 'Barra', CAST(0 AS BIT) AS AlertaLAB
FROM dbo.ADINGRESO A with(nolock)
INNER JOIN dbo.INPACIENT B with(nolock) ON A.IPCODPACI=B.IPCODPACI 
INNER JOIN dbo.ADACTIVID L with(nolock) ON B.CODACTIVI = L.codactivi
left outer JOIN (SELECT row_number() over( partition by NUMINGRES order by ID desc) IDparticion, NUMINGRES, TRIAGECLA, CODCONCEC FROM  dbo.ADTRIAGEU with(nolock) ) AS D ON D.IDparticion = 1 AND A.NUMINGRES = D.NUMINGRES 
left outer join dbo.INESPECIA c with(nolock) on a.CODESPTRA =c.CODESPECI
LEFT OUTER JOIN dbo.ADCONTURG E with(nolock) ON E.CODCONCEC = D.CODCONCEC
LEFT OUTER JOIN	dbo.INENTIDAD P with(nolock) ON P.CODENTIDA = B.CODENTIDA
LEFT OUTER JOIN dbo.INDIAGNOS Q with(nolock) ON Q.CODDIAGNO = (SELECT TOP 1 CODDIAGNO FROM INDIAGNOP with(nolock) WHERE IPCODPACI = B.IPCODPACI AND NUMINGRES = A.NUMINGRES AND CODDIAPRI = 1)  
WHERE IESTADOIN='' AND UFUINGMED=@UnidadFuncional AND UFUINGHOS IS NULL AND (UFUEGRMED IS NULL or DESTINOPAC = 1 ) AND DESTINOPAC IS NOT NULL

end