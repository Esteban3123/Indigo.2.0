	convert(varchar(10),FECHA4,103) As 'FECHA4', Rtrim(LOTE4) As 'LOTE4', 

	CASE ADENITIS  WHEN '1' THEN 'X' END AS 'ADENITIS',CASE ABSCESO WHEN '1' THEN 'X' END AS 'ABSCESO', CASE LINFADE WHEN '1' THEN 'X' END AS 'LINFADE',
