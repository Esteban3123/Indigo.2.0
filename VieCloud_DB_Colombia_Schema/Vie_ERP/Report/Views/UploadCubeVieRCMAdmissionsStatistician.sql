GO
EXEC sys.sp_addextendedproperty @name=N'MS_BR_Consumes', @value=N'DBO.ADINGRESO; DBO.INUNIFUNC; CONTRACT.CAREGROUP; Security.UserINT; DBO.SEGUSUARU; SECURITY.PERSONINT; DBO.INPACIENT; CONTRACT.HEALTHADMINISTRATOR; COMMON.CITY; DBO.HCHISPACA; DBO.INDIAGNOS; DBO.HCREGEGRE; DBO.ADTRIAGEU; DBO.ADCONTURG; DBO.INUBICACI; DBO.INMUNICIP; DBO.ADCENATEN', @level0type=N'SCHEMA', @level0name=N'Report', @level1type=N'VIEW', @level1name=N'UploadCubeVieRCMAdmissionsStatistician';
GO
EXEC sys.sp_addextendedproperty @name=N'MS_BR_Source', @value=N'ai_claude-opus-4-7_tier-c_2026-05-06', @level0type=N'SCHEMA', @level0name=N'Report', @level1type=N'VIEW', @level1name=N'UploadCubeVieRCMAdmissionsStatistician';
