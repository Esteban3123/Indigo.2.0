CREATE PROCEDURE [dbo].[SP_BuildingRes4505]
/*DECLARACION DE VARIABLES*/
@FechaInicial date,
@FechaFin date
/*,@Entidad nvarchar(10)*/
--Declare @ipcodpaci nvarchar(25)

AS 
BEGIN 
		SET NOCOUNT ON;

;WITH CTE_INGRESOS
	AS 
	(
	SELECT IFECHAING, ADI1.IPCODPACI, ADI1.NUMINGRES, INP.IPTIPODOC FROM dbo.ADINGRESO ADI1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON ADI1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRES)NUMINGRES, IPCODPACI FROM dbo.ADINGRESO WITH (NOLOCK) WHERE IFECHAING BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) ADI2
		ON ADI1.NUMINGRES=ADI2.NUMINGRES AND ADI1.IPCODPACI=ADI2.IPCODPACI
	)

,CTE_EXAMEN_FISICO
	AS
	(
	SELECT HCE1.FECREGSIS, PESOPACIE, TALLAPACI, HCE2.IPCODPACI , HCE1.NUMINGRES, INP.IPTIPODOC  FROM dbo.HCEXFISIC HCE1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCE1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMCONSEC)NUMCONSEC, IPCODPACI FROM dbo.HCEXFISIC WITH (NOLOCK) WHERE NUMINGRES IS NOT NULL AND FECREGITE BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCE2 
		ON  HCE1.NUMCONSEC=HCE2.NUMCONSEC AND HCE1.IPCODPACI=HCE2.IPCODPACI
	)

,CTE_GESTACION
	AS
	(
	SELECT HCR1.IPCODPACI, HCR1.NUMINGRCES, GESTACION, FECGESTA, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECGESTA BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR2 ON  HCR1.NUMINGRCES=HCR2.NUMINGRCES AND HCR1.IPCODPACI=HCR2.IPCODPACI
	)

,CTE_RIESGO_SIFILIS
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
        INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECSIFGES BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR12 ON  HCR1.NUMINGRCES=HCR12.NUMINGRCES AND HCR1.IPCODPACI=HCR12.IPCODPACI
	)

,CTE_RIESGO_HIPERTEN
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
        INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECHIPER BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR6 ON  HCR1.NUMINGRCES=HCR6.NUMINGRCES AND HCR1.IPCODPACI=HCR6.IPCODPACI
	)

,CTE_RIESGO_HIPOTIROIDISMO
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECHIPOTE BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR7 ON  HCR1.NUMINGRCES=HCR7.NUMINGRCES AND HCR1.IPCODPACI=HCR7.IPCODPACI
	)

,CTE_RIESGO_RESPIRATORIO
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECSINTO BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR13 ON  HCR1.NUMINGRCES=HCR13.NUMINGRCES AND HCR1.IPCODPACI=HCR13.IPCODPACI
	)

,CTE_RIESGO_TUBERCULOSIS
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECTUBER BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR14 ON  HCR1.NUMINGRCES=HCR14.NUMINGRCES AND HCR1.IPCODPACI=HCR14.IPCODPACI
	)

,CTE_RIESGO_LEPRA
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECLEPRA BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR10 ON  HCR1.NUMINGRCES=HCR10.NUMINGRCES AND HCR1.IPCODPACI=HCR10.IPCODPACI
	)

,CTE_RIESGO_OBESIDAD
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECOBEDES BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR11 ON  HCR1.NUMINGRCES=HCR11.NUMINGRCES AND HCR1.IPCODPACI=HCR11.IPCODPACI
	)

,CTE_RIESGO_MALTRATO
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT  INP WITH (NOLOCK)ON HCR1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECVICMAL BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR15 ON  HCR1.NUMINGRCES=HCR15.NUMINGRCES AND HCR1.IPCODPACI=HCR15.IPCODPACI
		)

,CTE_VIOLENCIA_SEXUAL
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC, CASE WHEN VICTVIOLSEX=1 THEN 1
             WHEN VICTVIOLESEXU=1 THEN 1
			 WHEN VICTVIOLSEX=2 THEN 2
             WHEN VICTVIOLESEXU=2 THEN 2
			 WHEN VICTVIOLSEX NOT IN (1,2,21) THEN VICTVIOLSEX
			 WHEN VICTVIOLSEX IS NULL THEN 21
			 WHEN VICTVIOLESEXU IS NULL THEN 21
			 END VICVIOLENCIASEX, 
			 CASE WHEN FECVICMAL IS NULL THEN FECVICVIOSEX
				  WHEN FECVICVIOSEX IS NULL THEN FECVICMAL	
				  END FECVIOLENCIASEX
						FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
			 LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
			 INNER JOIN(
			 SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECVICVIOSEX BETWEEN @FechaInicial AND @FechaFin AND GESTACION=1 GROUP BY IPCODPACI) HCR2 
			 ON  HCR1.NUMINGRCES=HCR2.NUMINGRCES AND HCR1.IPCODPACI=HCR2.IPCODPACI
	)

,CTE_RIESGO_TRANSM
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP WITH (NOLOCK) ON HCR1.IPCODPACI=INP.IPCODPACI
        INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP WITH (NOLOCK) WHERE NUMINGRCES IS NOT NULL AND FECINFTRA BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR8 ON  HCR1.NUMINGRCES=HCR8.NUMINGRCES AND HCR1.IPCODPACI=HCR8.IPCODPACI
	)
		
,CTE_RIESGO_MENTAL
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1 WITH (NOLOCK) 
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK)  ON HCR1.IPCODPACI=INP.IPCODPACI
        INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP  WITH (NOLOCK)  WHERE NUMINGRCES IS NOT NULL AND FECENFMEN BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR4 ON  HCR1.NUMINGRCES=HCR4.NUMINGRCES AND HCR1.IPCODPACI=HCR4.IPCODPACI
	)

,CTE_RIESGO_CERVIX
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1  WITH (NOLOCK) 
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK)  ON HCR1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP  WITH (NOLOCK)  WHERE NUMINGRCES IS NOT NULL AND FECCANCER BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR2 ON  HCR1.NUMINGRCES=HCR2.NUMINGRCES AND HCR1.IPCODPACI=HCR2.IPCODPACI
	)

,CTE_RIESGO_SENO
	AS
	(
	SELECT HCR1.*, INP.IPTIPODOC FROM dbo.HCRIESGOSP HCR1  WITH (NOLOCK) 
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK)  ON HCR1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMINGRCES) NUMINGRCES, IPCODPACI FROM dbo.HCRIESGOSP  WITH (NOLOCK)  WHERE NUMINGRCES IS NOT NULL AND FECCANSEN BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCR3 ON  HCR1.NUMINGRCES=HCR3.NUMINGRCES AND HCR1.IPCODPACI=HCR3.IPCODPACI
	)

,CTE_GINECOBSTETRICA
	AS
	(
	SELECT FECPROPAR, NOMSEMGES, HCA1.IPCODPACI, NUMINGRES, CAST(CANTPRENA AS FLOAT) CANTPRENA, CONTPRENA, INP.IPTIPODOC, CAST(INICONPRE AS FLOAT) INICONPRE, FECHISPAC  FROM dbo.HCANTGINE HCA1   WITH (NOLOCK) 
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK)  ON HCA1.IPCODPACI=INP.IPCODPACI
		INNER JOIN (SELECT MAX(NUMEFOLIO)NUMEFOLIO, IPCODPACI FROM dbo.HCANTGINE  WITH (NOLOCK)  WHERE NUMINGRES IS NOT NULL AND FECHISPAC BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HCA2 
		ON  HCA1.NUMEFOLIO=HCA2.NUMEFOLIO AND HCA1.IPCODPACI=HCA2.IPCODPACI
	)

,CTE_ATENCION_PARTO
	AS
	(
	SELECT FECINIATE, HCAT.IPCODPACI, NUMINGRES, INP.IPTIPODOC FROM dbo.HCATINPAR HCAT  WITH (NOLOCK) 
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK)  ON HCAT.IPCODPACI=INP.IPCODPACI WHERE FECINIATE BETWEEN @FechaInicial AND @FechaFin
	)

,CTE_SALIDA_HOSPITALIZACION
	AS
	(
	SELECT HCRE.IPCODPACI, FECALTPAC, NUMINGRES, INP.IPTIPODOC FROM dbo.HCREGEGRE HCRE  WITH (NOLOCK) 
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK)  ON HCRE.IPCODPACI=INP.IPCODPACI WHERE FECALTPAC BETWEEN @FechaInicial AND @FechaFin
	)

,CTE_HISTERECTOMIA
	AS
	(
	SELECT INDI.IPCODPACI, INP.IPTIPODOC, INDI.FECDIAGNO FROM dbo.INDIAGNOH  INDI  WITH (NOLOCK) 
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK) ON INDI.IPCODPACI=INP.IPCODPACI  WHERE CODDIAGNO IN ('N993','O822')
	)

,CTE_HISTORIA_CLINICA
	AS
	(
	SELECT HC1.FECHISPAC, HC1.IPCODPACI, HC1.NUMINGRES, HC1.CODDIAGNO, IND.NOMDIAGNO, INP.IPTIPODOC FROM dbo.HCHISPACA HC1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK) ON HC1.IPCODPACI=INP.IPCODPACI  
		INNER JOIN (SELECT MAX(NUMINGRES) NUMINGRES, MAX(FECHISPAC) FECHISPAC,  IPCODPACI FROM dbo.HCHISPACA  WITH (NOLOCK) WHERE NUMINGRES IS NOT NULL AND FECHISPAC BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HC2 ON  HC1.NUMINGRES=HC2.NUMINGRES AND HC1.IPCODPACI=HC2.IPCODPACI AND HC1.FECHISPAC=HC2.FECHISPAC
		INNER JOIN dbo.INDIAGNOS IND  WITH (NOLOCK) ON HC1.CODDIAGNO=IND.CODDIAGNO WHERE HC1.CODDIAGNO IN (SELECT CODDIAGNO FROM dbo.INDIAGNOS WHERE NOMDIAGNO LIKE '%PROTEICO%' OR NOMDIAGNO LIKE '% NUTRICI%' OR NOMDIAGNO LIKE '%TRANS%SEXUA%' OR NOMDIAGNO LIKE 'VIH' OR CODDIAGNO LIKE 'Z717' AND HC1.FECHISPAC  BETWEEN @FechaInicial AND @FechaFin) 																																																														
		GROUP BY HC1.FECHISPAC, HC1.IPCODPACI, HC1.CODDIAGNO, IND.NOMDIAGNO, INP.IPTIPODOC,HC1.NUMINGRES
	)

,CTE_HISTORIA_CLINICA_CANCER_CERVIX
	AS
	(
	SELECT HC1.FECHISPAC, HC1.IPCODPACI, HC1.NUMINGRES, HC1.CODDIAGNO, IND.NOMDIAGNO, INP.IPTIPODOC FROM dbo.HCHISPACA HC1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK) ON HC1.IPCODPACI=INP.IPCODPACI  
		INNER JOIN (SELECT MAX(NUMINGRES) NUMINGRES, MAX(FECHISPAC) FECHISPAC, IPCODPACI FROM dbo.HCHISPACA  WITH (NOLOCK) WHERE NUMINGRES IS NOT NULL AND FECHISPAC BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HC2 ON  HC1.NUMINGRES=HC2.NUMINGRES AND HC1.IPCODPACI=HC2.IPCODPACI AND HC1.FECHISPAC=HC2.FECHISPAC
		INNER JOIN dbo.INDIAGNOS IND  WITH (NOLOCK) ON HC1.CODDIAGNO=IND.CODDIAGNO WHERE HC1.CODDIAGNO IN (SELECT CODDIAGNO FROM dbo.INDIAGNOS WHERE CODDIAGNO IN ('D069','D067','C530','C531','D060','D061') AND HC1.FECHISPAC  BETWEEN @FechaInicial AND @FechaFin) 																																																														
		GROUP BY HC1.FECHISPAC, HC1.IPCODPACI, HC1.CODDIAGNO, IND.NOMDIAGNO, INP.IPTIPODOC,HC1.NUMINGRES
	)

,CTE_HISTORIA_CLINICA_CANCER_SENO
	AS
	(
	SELECT HC1.FECHISPAC, HC1.IPCODPACI, HC1.NUMINGRES, HC1.CODDIAGNO, IND.NOMDIAGNO, INP.IPTIPODOC FROM dbo.HCHISPACA HC1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK) ON HC1.IPCODPACI=INP.IPCODPACI  
		INNER JOIN (SELECT MAX(NUMINGRES) NUMINGRES, MAX(FECHISPAC) FECHISPAC, IPCODPACI FROM dbo.HCHISPACA  WITH (NOLOCK) WHERE NUMINGRES IS NOT NULL AND FECHISPAC BETWEEN @FechaInicial AND @FechaFin GROUP BY IPCODPACI) HC2 ON  HC1.NUMINGRES=HC2.NUMINGRES AND HC1.IPCODPACI=HC2.IPCODPACI AND HC1.FECHISPAC=HC2.FECHISPAC
		INNER JOIN dbo.INDIAGNOS IND  WITH (NOLOCK) ON HC1.CODDIAGNO=IND.CODDIAGNO WHERE HC1.CODDIAGNO IN (SELECT CODDIAGNO FROM dbo.INDIAGNOS WHERE CODDIAGNO IN  ('C500','C501','C502','C503','C504','C505','C506','C508','C509','D050','D051','D057','D059','D486') AND HC1.FECHISPAC  BETWEEN @FechaInicial AND @FechaFin) 																																																														
		GROUP BY HC1.FECHISPAC, HC1.IPCODPACI, HC1.CODDIAGNO, IND.NOMDIAGNO, INP.IPTIPODOC,HC1.NUMINGRES
	)

,CTE_HISTORIA_CLINICA_NUTRICION
	AS
	(
	SELECT HC1.FECHISPAC, HC1.IPCODPACI, HC1.NUMINGRES, HC1.CODDIAGNO, CODESPTRA, INP.IPTIPODOC FROM dbo.HCHISPACA HC1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK) ON HC1.IPCODPACI=INP.IPCODPACI  
		INNER JOIN (SELECT MAX(NUMINGRES) NUMINGRES, MAX(FECHISPAC) FECHISPAC, IPCODPACI FROM dbo.HCHISPACA  WITH (NOLOCK) WHERE NUMINGRES IS NOT NULL AND FECHISPAC BETWEEN @FechaInicial AND @FechaFin AND CODESPTRA IN ('051','052','113')   GROUP BY IPCODPACI) HC2 ON  HC1.NUMINGRES=HC2.NUMINGRES AND HC1.IPCODPACI=HC2.IPCODPACI AND HC1.FECHISPAC=HC2.FECHISPAC
		GROUP BY HC1.FECHISPAC, HC1.IPCODPACI, HC1.CODDIAGNO, CODESPTRA, INP.IPTIPODOC,HC1.NUMINGRES
	)

,CTE_HISTORIA_CLINICA_PSICOLOGIA
	AS
	(
	SELECT HC1.FECHISPAC, HC1.IPCODPACI, HC1.NUMINGRES, HC1.CODDIAGNO, CODESPTRA, INP.IPTIPODOC FROM dbo.HCHISPACA HC1 WITH (NOLOCK)
		LEFT JOIN dbo.INPACIENT INP  WITH (NOLOCK) ON HC1.IPCODPACI=INP.IPCODPACI  
		INNER JOIN (SELECT MAX(NUMINGRES) NUMINGRES, MAX(FECHISPAC) FECHISPAC, IPCODPACI FROM dbo.HCHISPACA  WITH (NOLOCK) WHERE NUMINGRES IS NOT NULL AND FECHISPAC BETWEEN @FechaInicial AND @FechaFin AND CODESPTRA IN ('071','133')   GROUP BY IPCODPACI) HC2 ON  HC1.NUMINGRES=HC2.NUMINGRES AND HC1.IPCODPACI=HC2.IPCODPACI AND HC1.FECHISPAC=HC2.FECHISPAC
		GROUP BY HC1.FECHISPAC, HC1.IPCODPACI, HC1.CODDIAGNO, CODESPTRA, INP.IPTIPODOC,HC1.NUMINGRES
	)
	
,CTE_TOTAL_LABORATORIO
	AS(
	/*ORDENES DE LABORATORIO AMBULATORIAS*/ 
	SELECT DISTINCT  DT.ORDTIP, INP.IPTIPODOC, INC.DESSERIPS, LB.CODSERIPS, LB.AUTO LB_AUTO, LB.IPCODPACI, LB.NUMINGRES, LB.FECORDMED, CR.AUTO CR_AUTO, CR.AUTOLABOR CR_AUTOLABOR, CR.ORDEN_INDIGO, CR.FECGENERA, CR.FECREGIST, CR.FECSERIPS, BD.AUTO BD_AUTO, BD.CODCONCEC, BD.ANALITO, BD.VALOR, BD.VALORMINIMO, BD.VALORMAXIMO, BD.AUTOLABOR, BD.CLASIFICACION  
	FROM DBO.AMBORDLAB LB   WITH (NOLOCK) 	
			LEFT JOIN DBO.INPACIENT INP  WITH (NOLOCK) ON LB.IPCODPACI=INP.IPCODPACI  
			LEFT JOIN DBO.INCUPSIPS INC  WITH (NOLOCK) ON LB.CODSERIPS=INC.CODSERIPS
			LEFT JOIN DBO.INTERDETA DT  WITH (NOLOCK) ON LB.AUTO=DT.AUTOLABOR 
			LEFT JOIN DBO.INTERCABE CB  WITH (NOLOCK) ON DT.CODCONCEC=CB.AUTO AND LB.NUMINGRES=CB.NUMINGRES
			LEFT JOIN DBO.INTERCTRL CR  WITH (NOLOCK) ON DT.AUTOLABOR=CR.AUTOLABOR 
			LEFT JOIN DBO.INTERLABD BD  WITH (NOLOCK) ON CR.AUTOLABOR=BD.AUTOLABOR
			WHERE DT.ORDTIP LIKE 'AMB' AND LB.CODSERIPS IN (SELECT CODSERIPS FROM DBO.INCUPSIPS  WITH (NOLOCK)  WHERE DESSERIPS LIKE '%VIRUS DE INMUNODEFICIENCIA HUMANA%' OR DESSERIPS LIKE '%TREPO%' OR (DESSERIPS LIKE '%HEMOGLOB%' AND ANALITO LIKE '%HEMOGLOB%') OR (DESSERIPS LIKE '%HEPATITIS B%' AND DESSERIPS NOT LIKE 'VACUNA%') 
            OR (CODSERIPS IN ('903876','903895') AND ANALITO LIKE '%HEMOGLOB%')
		    OR (CODSERIPS IN ('903426','903427') AND ANALITO LIKE 'HEMOGLOBINA TOTAL')
		    OR CODSERIPS IN ('906492','904903','892901','898001','702203%','033201%','876801' ,'876802', '902213','903841','901101')) 
		    AND BD.AUTO IS NOT NULL
			AND CR.FECREGIST BETWEEN @FECHAINICIAL AND @FECHAFIN 
UNION ALL
	/*ORDENES DE LABORATORIO INTRAHOSPITALARIAS*/ 
	SELECT DISTINCT  DT.ORDTIP, INP.IPTIPODOC, INC.DESSERIPS, LB.CODSERIPS, LB.AUTO LB_AUTO, LB.IPCODPACI, LB.NUMINGRES, LB.FECORDMED, CR.AUTO CR_AUTO, CR.AUTOLABOR CR_AUTOLABOR, CR.ORDEN_INDIGO, CR.FECGENERA, CR.FECREGIST, CR.FECSERIPS, BD.AUTO BD_AUTO, BD.CODCONCEC, BD.ANALITO, BD.VALOR, BD.VALORMINIMO, BD.VALORMAXIMO, BD.AUTOLABOR, BD.CLASIFICACION  
		FROM DBO.HCORDLABO LB  WITH (NOLOCK)    
			LEFT JOIN DBO.INPACIENT INP  WITH (NOLOCK) ON LB.IPCODPACI=INP.IPCODPACI  
			LEFT JOIN DBO.INCUPSIPS INC  WITH (NOLOCK) ON LB.CODSERIPS=INC.CODSERIPS
			LEFT JOIN DBO.INTERDETA DT  WITH (NOLOCK) ON LB.AUTO=DT.AUTOLABOR 
			LEFT JOIN DBO.INTERCABE CB  WITH (NOLOCK) ON DT.CODCONCEC=CB.AUTO AND LB.NUMINGRES=CB.NUMINGRES
